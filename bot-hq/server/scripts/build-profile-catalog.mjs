// Rebuild the packaged catalog from the canonical handoff. The installed app
// imports the generated TypeScript/JavaScript only; it never reads this source.
// Run with --check to verify the committed catalog matches the handoff exactly.
import fs from 'node:fs';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const source = new URL('../../../mortgage-bot-team/04-bot-profiles.md', import.meta.url);
const output = new URL('../src/local-text-profiles.ts', import.meta.url);
const text = fs.readFileSync(source, 'utf8');
const roles = [
  ['mortgage-team-lead', 'Mortgage Team Lead'],
  ['loan-officer-assistant', 'Loan Officer Assistant'],
  ['loan-processing-assistant', 'Loan Processing Assistant'],
  ['mortgage-marketing-assistant', 'Mortgage Marketing Assistant'],
  ['mortgage-email-assistant', 'Mortgage Email Assistant'],
];
const sections = text.split(/^## /m).slice(1);
if (sections.length !== roles.length) throw new Error('Expected exactly five canonical mortgage profiles.');
const profiles = [{ id: 'general', name: 'General chat', label: 'Text assistant',
  about: 'A general text-only conversation, separate from the five mortgage draft assistants.',
  draft: true, instructions: '' }];
for (const [index, [id, name]] of roles.entries()) {
  const section = sections[index];
  const actualName = /^\*\*Name:\*\* (.+)$/m.exec(section)?.[1];
  const label = /^\*\*Label:\*\* (.+)$/m.exec(section)?.[1];
  const about = /\*\*About:\*\*\n\n([\s\S]*?)\n\n\*\*Instructions:\*\*/.exec(section)?.[1];
  // Keep the block bytes verbatim, including the terminal newline before its fence.
  const instructions = /```text\n([\s\S]*?)```/.exec(section)?.[1];
  if (actualName !== name || !label || !about || !instructions) throw new Error(`Canonical profile is incomplete: ${name}`);
  profiles.push({ id, name, label, about, draft: true, instructions });
}
const generated = `// Generated by server/scripts/build-profile-catalog.mjs; do not edit instruction text here.
// Canonical source: mortgage-bot-team/04-bot-profiles.md. Runtime is self-contained.
export const profileSourceSha256 = ${JSON.stringify(crypto.createHash('sha256').update(text).digest('hex'))};
export interface LocalTextProfile { id: string; name: string; label: string; about: string; draft: true; instructions: string }
export const localTextProfiles: readonly Readonly<LocalTextProfile>[] = Object.freeze(${JSON.stringify(profiles, null, 2)}.map((profile) => Object.freeze({ ...profile, draft: true as const })));
export const localTextProfile = (id: string): Readonly<LocalTextProfile> | undefined => localTextProfiles.find((profile) => profile.id === id);
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== generated) throw new Error('Packaged catalog differs from the canonical profiles; rebuild it.');
  console.log('PASS: packaged catalog matches all five canonical profile blocks exactly.');
} else {
  fs.writeFileSync(output, generated);
  console.log(`Generated ${fileURLToPath(output)} with five exact draft profiles and General chat.`);
}
