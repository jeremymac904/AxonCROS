// Package only the explicitly approved local Markdown research. Installed code
// never searches the filesystem or reads repository paths at runtime.
import fs from 'node:fs';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const allowed = [
  ['team-overview', '00-START-HERE.md'],
  ['team-operating-model', '01-team-operating-model.md'],
  ['loan-workflow', '02-loan-workflow.md'],
  ['controls-and-sources', '03-controls-and-sources.md'],
  ['bot-profiles', '04-bot-profiles.md'],
  ['acceptance-tests', '05-acceptance-tests.md'],
  ['deployment-plan', '06-deployment-plan.md'],
  ['platform-overview', '07-platform-training/00-START-HERE.md'],
  ['loan-factory-arive', '07-platform-training/01-loan-factory-arive.md'],
  ['lendingpad-encompass', '07-platform-training/02-lendingpad-encompass.md'],
  ['sonar-uwm-rocket', '07-platform-training/03-sonar-uwm-rocket.md'],
  ['platform-skill', '07-platform-training/04-platform-skill.md'],
];
const documents = allowed.map(([id, relative]) => {
  const source = new URL(`../../../mortgage-bot-team/${relative}`, import.meta.url);
  if (!fs.lstatSync(source).isFile() || fs.lstatSync(source).isSymbolicLink()) throw new Error(`Research source must be a regular file: ${relative}`);
  const bytes = fs.readFileSync(source);
  const text = bytes.toString('utf8');
  if (!Buffer.from(text, 'utf8').equals(bytes)) throw new Error(`Research source must be valid UTF-8: ${relative}`);
  const title = /^# (.+)$/m.exec(text)?.[1];
  if (!title) throw new Error(`Research title missing: ${relative}`);
  const lines = text.split('\n'); if (lines.at(-1) === '') lines.pop();
  return { id, title, path: `mortgage-bot-team/${relative}`,
    sha256: crypto.createHash('sha256').update(bytes).digest('hex'), lineCount: lines.length, text };
});
const snapshotId = crypto.createHash('sha256').update(JSON.stringify(documents.map(({ id, path, sha256 }) => ({ id, path, sha256 })))).digest('hex');
const output = new URL('../src/local-research-catalog.ts', import.meta.url);
const generated = `// Generated by server/scripts/build-research-catalog.mjs. Do not edit document text here.
// Exact allowlisted research snapshot; no runtime repository/filesystem dependency.
export interface ResearchDocument { id: string; title: string; path: string; sha256: string; lineCount: number; text: string }
export const researchSnapshotId = ${JSON.stringify(snapshotId)};
export const researchSnapshotDate = '2026-11-12'; // Initial local research release date, not regeneration or source verification date.
export const researchNotice = 'Packaged local research snapshot: baseline November 11, 2026, with local implementation notes where present. This is dated, unverified reference material, not live legal, lender or account authority. Historical setup claims may be stale. A citation identifies supplied text, not verified currency or permission to act.';
export const researchDocuments: readonly Readonly<ResearchDocument>[] = Object.freeze(${JSON.stringify(documents, null, 2)}.map((document) => Object.freeze(document)));
export const researchDocument = (id: string): Readonly<ResearchDocument> | undefined => researchDocuments.find((document) => document.id === id);
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== generated) throw new Error('Packaged research differs from the approved source files; regenerate it.');
  console.log('PASS: all 12 packaged research documents match their exact allowlisted source bytes.');
} else {
  fs.writeFileSync(output, generated);
  console.log(`Generated ${fileURLToPath(output)} from 12 allowlisted documents.`);
}
